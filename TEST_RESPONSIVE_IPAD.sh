    echo "  Expected Layout:"
    if [ "$portrait_width" -lt 900 ]; then
        echo "    ✓ Compact Mode (< 900px)"
        echo "    ✓ Sidebar: Collapsed (84px, icons only)"
        echo "    ✓ Tiles: 1 per row (100% width)"
        echo "    ✓ Popular Dishes + Low Stock: Stacked vertically"
        echo "    ✓ Chart: Chips wrap vertically"
    elif [ "$portrait_width" -lt 1180 ]; then
        echo "    ✓ Medium Mode (900-1179px)"
        echo "    ✓ Sidebar: Expanded (210px)"
        echo "    ✓ Tiles: 2 per row (48% width)"
        echo "    ✓ Popular Dishes + Low Stock: 2 columns below chart"
        echo "    ✓ Chart: Chips on single line"
