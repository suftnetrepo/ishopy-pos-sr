        echo "    ✓ Large Mode (≥ 1180px)"
        echo "    ✓ Sidebar: Expanded (210px)"
        echo "    ✓ Tiles: 3 per row (31.5% width)"
        echo "    ✓ Popular Dishes + Low Stock: Right rail (280px)"
    fi
    echo ""
    
    echo "🔄 LANDSCAPE MODE (${landscape_width}px width)"
    echo "  Expected Layout:"
    if [ "$landscape_width" -lt 900 ]; then
        echo "    ✓ Compact Mode (< 900px)"
    elif [ "$landscape_width" -lt 1180 ]; then
        echo "    ✓ Medium Mode (900-1179px)"
    else
        echo "    ✓ Large Mode (≥ 1180px)"
    fi
    echo ""
    
    echo "✅ Verification Checklist:"
    echo "  [ ] Portrait mode renders correctly"
    echo "  [ ] Landscape mode renders correctly"
    echo "  [ ] No text cutoff or overflow"
    echo "  [ ] No white space artifacts"
    echo "  [ ] All buttons/icons clickable"
    echo "  [ ] Scroll areas work smoothly"
    echo "  [ ] Sidebar labels visible (when expanded)"
    echo ""
